void put_dec(uchar x,uchar y, uint16_t val)
{

        char n;
        char buffer[4]={0x30,0x30,0x30,0x30};

	unsigned char c;


	if (val == 0)
        {
            return;
        }

	n=3;
        while(val != 0)
	{
		 c = val % 10;
		buffer[n--] = '0' + c;
		val = val / 10;
	}
        buffer[4] = 0;
        put_text(x,y, buffer,4);

}

