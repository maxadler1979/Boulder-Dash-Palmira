// --- Idle animation state (C64: __BlinkFlag $bf, __TapFootFlag $be) ---
// Adapted for RK86: C64 changes only 2 of 4 char-tiles (eyes/feet);
// RK86 swaps the entire 12x12 sprite, so events are spread evenly
// via idle_tick counter instead of independent random triggers.
unsigned char idle_tick;         // idle frame counter (wraps at 255, ~32 sec)
unsigned char idle_blink_timer;  // 0=off, 2=morg1→1=morg2→0=done (2-tick blink seq)
unsigned char idle_tap_timer;    // 0=off, >0=countdown for 4-phase tap sequence
unsigned char idle_tap_counter;  // sub-tick counter per tap phase (3 ticks/phase)
unsigned char idle_tap_phase;    // 3=ruki, 2=ruki_noga+click, 1=ruki, 0=ruki_noga+click
unsigned char *idle_sprite_ptr = stay;  // default = base stay (init before sprites_anim)

// ============================================================
// update_idle_sprite: set idle_sprite_ptr based on blink/tap
// flags. Called from game_tick_step() before sprites_anim().
// Mirrors C64 AnimateRockford__Bored ($786c).
// ============================================================
void update_idle_sprite(void)
{
    char blink = (idle_blink_timer > 0);
    char blink2 = (idle_blink_timer == 1);   // 1=morg2 (timer counts 2→1→0)
    char tap = (idle_tap_timer > 0);
    char foot_down = (tap && (idle_tap_phase == 2 || idle_tap_phase == 0));
    char arms_up  = (tap && (idle_tap_phase == 3 || idle_tap_phase == 1));

    if (!blink && !tap)
        idle_sprite_ptr = (unsigned char*)stay;
    else if (blink && !tap)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_morg2 : (unsigned char*)stay_morg1;
    else if (!blink && arms_up && !foot_down)
        idle_sprite_ptr = (unsigned char*)stay_ruki;
    else if (!blink && foot_down)
        idle_sprite_ptr = (unsigned char*)stay_ruki_noga;
    else if (blink && foot_down)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_ruki_noga_morg2 : (unsigned char*)stay_ruki_noga_morg1;
    else if (blink && arms_up)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_morg2 : (unsigned char*)stay_morg1;  // blink wins over arms
    else
        idle_sprite_ptr = (unsigned char*)stay;
}


