/*
 * tiles.c — все игровые тайлы 12x12.
 *
 * Формат спрайта на Радио-86РК
 * ---------------------------
 * Экран ВГ75 — знакоместовая сетка: один байт видеопамяти = один символ
 * знакогенератора. Мы зашиваем в знакогенератор (RU10, 0xD800) псевдографику
 * 2x3: шесть пикселей знакоместа кодируются младшими 6 битами кода символа.
 *
 * Тайл 12x12 пикселей = 6 знакомест в ширину x 4 в высоту = 24 байта подряд:
 *
 *     байт  0  1  2  3  4  5     <- верхний ряд, 6 колонок
 *     байт  6  7  8  9 10 11
 *     байт 12 13 14 15 16 17
 *     байт 18 19 20 21 22 23     <- нижний ряд
 *
 * Блиттер (show_window / put_sbitmap) кладёт эти 24 байта в видеопамять
 * с шагом VIDEO_BPL-5 = 73: после 6 байт строки HL указывает на последний
 * записанный байт, +73 даёт начало следующей строки тайла.
 *
 * Имена массивов — это и есть символы линкера (_d0, _beton, _am_1, ...).
 * labirint.c берёт их через MapObj[код_объекта]; sprites_anim() каждый
 * тик переписывает указатели анимированных клеток (алмаз, амёба, выход...).
 */

