unsigned char idle_tick;
unsigned char idle_blink_timer;
unsigned char idle_tap_timer;
unsigned char idle_tap_counter;
unsigned char idle_tap_phase;
unsigned char *idle_sprite_ptr = stay;

void update_idle_sprite(void)
{
    char blink = (idle_blink_timer > 0);
    char blink2 = (idle_blink_timer == 1);
    char tap = (idle_tap_timer > 0);
    char foot_down = (tap && (idle_tap_phase == 2 || idle_tap_phase == 0));
    char arms_up  = (tap && (idle_tap_phase == 3 || idle_tap_phase == 1));

    if (!blink && !tap)
        idle_sprite_ptr = (unsigned char*)stay;
    else if (blink && !tap)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_morg2 : (unsigned char*)stay_morg1;
    else if (!blink && arms_up && !foot_down)
        idle_sprite_ptr = (unsigned char*)stay_ruki;
    else if (!blink && foot_down)
        idle_sprite_ptr = (unsigned char*)stay_ruki_noga;
    else if (blink && foot_down)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_ruki_noga_morg2 : (unsigned char*)stay_ruki_noga_morg1;
    else if (blink && arms_up)
        idle_sprite_ptr = blink2 ? (unsigned char*)stay_morg2 : (unsigned char*)stay_morg1;
    else
        idle_sprite_ptr = (unsigned char*)stay;
}
